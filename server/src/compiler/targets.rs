// DNA Synthesis Cost Estimator
// ═══════════════════════════════════════════════════════════════════════

pub struct CostEstimator;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CostEstimate {
    pub total_bp: usize,
    pub total_cost_usd: f64,
    pub providers: Vec<ProviderQuote>,
    pub assembly_cost: f64,
    pub per_circuit: Vec<CircuitCost>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderQuote {
    pub provider: String,
    pub price_per_bp: f64,
    pub total_price: f64,
    pub turnaround_days: u32,
    pub complexity_surcharge: f64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CircuitCost {
    pub name: String,
    pub total_bp: usize,
    pub num_parts: usize,
    pub synthesis_cost: f64,
    pub assembly_cost: f64,
}

impl CostEstimator {
    /// Estimate DNA synthesis costs from major providers
    pub fn estimate(program: &BioIRProgram) -> CostEstimate {
        let mut total_bp = 0;
        let mut per_circuit = Vec::new();

        for circuit in &program.circuits {
            let mut circuit_bp = 0;
            let mut num_parts = 0;

            for tu in &circuit.transcription_units {
                circuit_bp += tu.promoter.sequence.len();
                circuit_bp += tu.rbs.sequence.len();
                circuit_bp += tu.cds.dna_sequence.len();
                if let Some(ref term) = tu.terminator {
                    circuit_bp += term.sequence.len();
                }
                // Count parts
                num_parts += 3; // promoter + RBS + CDS
                if tu.terminator.is_some() {
                    num_parts += 1;
                }
                num_parts += tu.coding_sequences.len().saturating_sub(1); // extra CDS in polycistronic
            }

            let synthesis_cost = circuit_bp as f64 * 0.09; // ~$0.09/bp average
            let assembly_cost = num_parts as f64 * 15.0; // ~$15 per assembly reaction

            per_circuit.push(CircuitCost {
                name: circuit.name.clone(),
                total_bp: circuit_bp,
                num_parts,
                synthesis_cost,
                assembly_cost,
            });

            total_bp += circuit_bp;
        }

        let gc_high = program.circuits.iter().any(|c| {
            c.transcription_units.iter().any(|tu| {
                let gc: usize = tu
                    .cds
                    .dna_sequence
                    .chars()
                    .filter(|c| matches!(c, 'G' | 'C' | 'g' | 'c'))
                    .count();
                let len = tu.cds.dna_sequence.len().max(1);
                (gc as f64 / len as f64) > 0.65 || (gc as f64 / len as f64) < 0.25
            })
        });

        let complexity_surcharge = if gc_high { 0.15 } else { 0.0 };

        let providers = vec![
            ProviderQuote {
                provider: "Twist Bioscience".to_string(),
                price_per_bp: 0.07,
                total_price: total_bp as f64 * 0.07 * (1.0 + complexity_surcharge),
                turnaround_days: 15,
                complexity_surcharge: total_bp as f64 * 0.07 * complexity_surcharge,
            },
            ProviderQuote {
                provider: "IDT (gBlocks)".to_string(),
                price_per_bp: 0.10,
                total_price: total_bp as f64 * 0.10 * (1.0 + complexity_surcharge),
                turnaround_days: 5,
                complexity_surcharge: total_bp as f64 * 0.10 * complexity_surcharge,
            },
            ProviderQuote {
                provider: "GenScript".to_string(),
                price_per_bp: 0.09,
                total_price: total_bp as f64 * 0.09 * (1.0 + complexity_surcharge),
                turnaround_days: 10,
                complexity_surcharge: total_bp as f64 * 0.09 * complexity_surcharge,
            },
            ProviderQuote {
                provider: "Eurofins Genomics".to_string(),
                price_per_bp: 0.12,
                total_price: total_bp as f64 * 0.12 * (1.0 + complexity_surcharge),
                turnaround_days: 12,
                complexity_surcharge: total_bp as f64 * 0.12 * complexity_surcharge,
            },
        ];

        let assembly_cost = per_circuit.iter().map(|c| c.assembly_cost).sum();
        let total_cost = providers
            .iter()
            .map(|p| p.total_price)
            .min_by(|a, b| a.partial_cmp(b).unwrap())
            .unwrap_or(0.0)
            + assembly_cost;

        CostEstimate {
            total_bp,
            total_cost_usd: total_cost,
            providers,
            assembly_cost,
            per_circuit,
        }
    }

    /// Generate a human-readable cost report
    pub fn generate_report(estimate: &CostEstimate) -> String {
        let mut report = String::new();
        report.push_str("╔══════════════════════════════════════════════════════╗\n");
        report.push_str("║       DNA SYNTHESIS COST ESTIMATE                    ║\n");
        report.push_str("╠══════════════════════════════════════════════════════╣\n\n");

        report.push_str(&format!("Total construct size: {} bp\n", estimate.total_bp));
        report.push_str(&format!(
            "Assembly reactions: {}\n\n",
            estimate.per_circuit.len()
        ));

        report.push_str("┌─────────────────────────┬──────────┬──────────┬────────┐\n");
        report.push_str("│ Provider                │ $/bp     │ Total    │ Days   │\n");
        report.push_str("├─────────────────────────┼──────────┼──────────┼────────┤\n");
        for p in &estimate.providers {
            report.push_str(&format!(
                "│ {:<23} │ ${:.3}   │ ${:>7.2} │ {:>4}   │\n",
                p.provider, p.price_per_bp, p.total_price, p.turnaround_days
            ));
        }
        report.push_str("└─────────────────────────┴──────────┴──────────┴────────┘\n\n");

        report.push_str("Per-circuit breakdown:\n");
        for c in &estimate.per_circuit {
            report.push_str(&format!(
                "  • {}: {} bp, {} parts → synthesis ${:.2} + assembly ${:.2}\n",
                c.name, c.total_bp, c.num_parts, c.synthesis_cost, c.assembly_cost
            ));
        }

        report.push_str(&format!(
            "\nEstimated total (cheapest synthesis + assembly): ${:.2}\n",
            estimate.total_cost_usd
        ));

        report
    }
}

