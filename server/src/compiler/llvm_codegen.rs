#![allow(dead_code)]
//! LLVM IR Code Generation for BioScript
//!
//! This module generates LLVM IR that represents genetic circuits as computational
//! models. This is a novel approach in synthetic biology — using LLVM's optimization
//! infrastructure to analyze and optimize biological circuits.
//!
//! The mapping from biology to LLVM IR:
//! - **Promoter** → Function that computes transcription rate
//! - **RBS** → Function that computes translation initiation rate
//! - **CDS** → Global constant (DNA/protein sequence data)
//! - **Regulatory Link** → Hill function implementation
//! - **Circuit** → Module with composition of all TU functions
//! - **Kill Switch** → Conditional branch with toxin production
//!
//! This allows:
//! 1. Static analysis of circuit behavior using LLVM passes
//! 2. Simulation by JIT-compiling the circuit model
//! 3. Optimization of numerical parameters
//! 4. Cross-compilation to different target architectures (for embedded biosensors)
//!
//! Since inkwell (LLVM Rust bindings) requires LLVM to be installed, this module
//! generates LLVM IR as text (.ll format) which can be processed by any LLVM toolchain.

use std::fmt::Write;
use crate::compiler::bio_ir::*;

/// Configuration for LLVM IR generation
#[derive(Debug, Clone)]
pub struct LlvmConfig {
    /// Target triple (default: host)
    pub target_triple: String,
    /// Optimization level for generated IR
    pub opt_level: LlvmOptLevel,
    /// Include debug metadata
    pub debug_info: bool,
    /// Generate simulation harness
    pub simulation_harness: bool,
    /// Data layout string
    pub data_layout: String,
}

#[derive(Debug, Clone)]
pub enum LlvmOptLevel {
    O0, // No optimization — faithful representation
    O1, // Basic — constant folding
    O2, // Standard — inlining, loop optimization
    O3, // Aggressive — vectorization, aggressive inlining
}

impl Default for LlvmConfig {
    fn default() -> Self {
        Self {
            target_triple: "x86_64-pc-windows-msvc".to_string(),
            opt_level: LlvmOptLevel::O2,
            debug_info: true,
            simulation_harness: true,
            data_layout: "e-m:w-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128".to_string(),
        }
    }
}

/// LLVM IR Generator
pub struct LlvmCodeGen {
    config: LlvmConfig,
    ir: String,
    /// Counter for anonymous values
    reg_counter: usize,
}

impl LlvmCodeGen {
    pub fn new(config: LlvmConfig) -> Self {
        Self {
            config,
            ir: String::with_capacity(8192),
            reg_counter: 0,
        }
    }

    fn next_reg(&mut self) -> String {
        self.reg_counter += 1;
        format!("%{}", self.reg_counter)
    }

    /// Generate LLVM IR for a BioIR program
    pub fn generate(&mut self, program: &BioIRProgram) -> String {
        self.ir.clear();
        self.reg_counter = 0;

        // Module header
        self.emit_header(program);

        // Type definitions
        self.emit_types();

        // Global constants — DNA sequences, part parameters
        self.emit_globals(program);

        // Hill function (core of regulation modeling)
        self.emit_hill_function();

        // Promoter activity functions
        for circuit in &program.circuits {
            self.emit_circuit(circuit);
        }

        // Simulation harness (ODE system)
        if self.config.simulation_harness {
            self.emit_simulation_harness(program);
        }

        // Main entry point
        self.emit_main(program);

        // Module metadata
        self.emit_metadata(program);

        self.ir.clone()
    }

    // ─── Module Header ────────────────────────────────────────────────

    fn emit_header(&mut self, program: &BioIRProgram) {
        writeln!(self.ir, "; ============================================================").unwrap();
        writeln!(self.ir, "; BioScript LLVM IR — Generated by SynBio-LLVM Compiler").unwrap();
        writeln!(self.ir, "; Program: {}", program.name).unwrap();
        if let Some(ref host) = program.host {
            writeln!(self.ir, "; Host: {} ({})", host.name, host.strain).unwrap();
        }
        writeln!(self.ir, "; Circuits: {}", program.circuits.len()).unwrap();
        writeln!(self.ir, "; ============================================================").unwrap();
        writeln!(self.ir).unwrap();
        writeln!(self.ir, "source_filename = \"{}.bio\"", program.name).unwrap();
        writeln!(self.ir, "target datalayout = \"{}\"", self.config.data_layout).unwrap();
        writeln!(self.ir, "target triple = \"{}\"", self.config.target_triple).unwrap();
        writeln!(self.ir).unwrap();
    }

    // ─── Type Definitions ─────────────────────────────────────────────

    fn emit_types(&mut self) {
        writeln!(self.ir, "; ---- Biological Types ----").unwrap();
        writeln!(self.ir).unwrap();

        // TranscriptionUnit state: [promoter_activity, mRNA_level, protein_level]
        writeln!(self.ir, "; TU state: promoter_activity (f64), mRNA_count (f64), protein_count (f64)").unwrap();
        writeln!(self.ir, "%TUState = type {{ double, double, double }}").unwrap();
        writeln!(self.ir).unwrap();

        // Regulatory parameters
        writeln!(self.ir, "; Hill function params: Vmax, K_half, n (hill coefficient)").unwrap();
        writeln!(self.ir, "%HillParams = type {{ double, double, double }}").unwrap();
        writeln!(self.ir).unwrap();

        // Circuit state vector
        writeln!(self.ir, "; Circuit state: array of TU states + time").unwrap();
        writeln!(self.ir, "%CircuitState = type {{ double, [16 x %TUState] }}").unwrap();
        writeln!(self.ir).unwrap();

        // Simulation result
        writeln!(self.ir, "%SimResult = type {{ double, double, i32 }}  ; time, total_protein, num_steps").unwrap();
        writeln!(self.ir).unwrap();
    }

    // ─── Global Constants ─────────────────────────────────────────────

    fn emit_globals(&mut self, program: &BioIRProgram) {
        writeln!(self.ir, "; ---- Global Constants ----").unwrap();
        writeln!(self.ir).unwrap();

        // Biological constants
        writeln!(self.ir, "@ATP_PER_NUCLEOTIDE = private constant double 2.0").unwrap();
        writeln!(self.ir, "@ATP_PER_AMINOACID = private constant double 4.0").unwrap();
        writeln!(self.ir, "@MRNA_DEGRADATION_RATE = private constant double 0.0023  ; ~5 min half-life in E. coli").unwrap();
        writeln!(self.ir, "@PROTEIN_DEGRADATION_RATE = private constant double 0.00019  ; ~60 min half-life").unwrap();
        writeln!(self.ir, "@RIBOSOME_SPEED = private constant double 15.0  ; AA per second").unwrap();
        writeln!(self.ir, "@RNAP_SPEED = private constant double 50.0  ; nt per second").unwrap();
        writeln!(self.ir).unwrap();

        // Per-circuit constants
        for circuit in &program.circuits {
            writeln!(self.ir, "; Constants for circuit: {}", circuit.name).unwrap();

            for (i, tu) in circuit.transcription_units.iter().enumerate() {
                let prefix = format!("@{}_TU{}", circuit.name, i);

                // Promoter parameters
                writeln!(self.ir, "{}_promoter_strength = private constant double {:.6}",
                    prefix, tu.promoter.strength).unwrap();
                writeln!(self.ir, "{}_promoter_dg = private constant double {:.6}",
                    prefix, tu.promoter.delta_g).unwrap();

                // RBS parameters
                writeln!(self.ir, "{}_rbs_rate = private constant double {:.6}",
                    prefix, tu.rbs.translation_rate).unwrap();
                writeln!(self.ir, "{}_rbs_dg = private constant double {:.6}",
                    prefix, tu.rbs.delta_g).unwrap();

                // CDS length
                writeln!(self.ir, "{}_cds_length = private constant i32 {}",
                    prefix, tu.cds.dna_sequence.len()).unwrap();
                writeln!(self.ir, "{}_protein_length = private constant i32 {}",
                    prefix, tu.cds.amino_sequence.len()).unwrap();

                // DNA sequence as constant data
                let seq_bytes: Vec<String> = tu.cds.dna_sequence.bytes()
                    .take(100) // Truncate for readability
                    .map(|b| format!("i8 {}", b))
                    .collect();
                if !seq_bytes.is_empty() {
                    writeln!(self.ir, "{}_sequence = private constant [{} x i8] [{}]",
                        prefix, seq_bytes.len(), seq_bytes.join(", ")).unwrap();
                }

                writeln!(self.ir).unwrap();
            }

            // Regulatory link parameters
            for (i, link) in circuit.regulatory_links.iter().enumerate() {
                let prefix = format!("@{}_reg{}", circuit.name, i);
                writeln!(self.ir, "{}_strength = private constant double {:.6}",
                    prefix, link.strength).unwrap();
                writeln!(self.ir, "{}_hill_n = private constant double {:.6}",
                    prefix, link.hill_coefficient).unwrap();
                writeln!(self.ir, "{}_k_half = private constant double {:.6}",
                    prefix, link.k_half).unwrap();
            }
            writeln!(self.ir).unwrap();
        }
    }

    // ─── Hill Function ────────────────────────────────────────────────

    fn emit_hill_function(&mut self) {
        writeln!(self.ir, "; ---- Hill Function (core regulatory model) ----").unwrap();
        writeln!(self.ir).unwrap();

        // Activation Hill function: f(x) = Vmax * x^n / (K^n + x^n)
        writeln!(self.ir, "define private double @hill_activation(double %x, double %vmax, double %k, double %n) #0 {{").unwrap();
        writeln!(self.ir, "entry:").unwrap();
        writeln!(self.ir, "  %x_n = call double @llvm.pow.f64(double %x, double %n)").unwrap();
        writeln!(self.ir, "  %k_n = call double @llvm.pow.f64(double %k, double %n)").unwrap();
        writeln!(self.ir, "  %denom = fadd double %k_n, %x_n").unwrap();
        writeln!(self.ir, "  %ratio = fdiv double %x_n, %denom").unwrap();
        writeln!(self.ir, "  %result = fmul double %vmax, %ratio").unwrap();
        writeln!(self.ir, "  ret double %result").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();

        // Repression Hill function: f(x) = Vmax * K^n / (K^n + x^n)
        writeln!(self.ir, "define private double @hill_repression(double %x, double %vmax, double %k, double %n) #0 {{").unwrap();
        writeln!(self.ir, "entry:").unwrap();
        writeln!(self.ir, "  %x_n = call double @llvm.pow.f64(double %x, double %n)").unwrap();
        writeln!(self.ir, "  %k_n = call double @llvm.pow.f64(double %k, double %n)").unwrap();
        writeln!(self.ir, "  %denom = fadd double %k_n, %x_n").unwrap();
        writeln!(self.ir, "  %ratio = fdiv double %k_n, %denom").unwrap();
        writeln!(self.ir, "  %result = fmul double %vmax, %ratio").unwrap();
        writeln!(self.ir, "  ret double %result").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();

        // Dual regulation (activation AND repression)
        writeln!(self.ir, "define private double @hill_dual(double %activator, double %repressor, double %vmax, double %ka, double %kr, double %na, double %nr) #0 {{").unwrap();
        writeln!(self.ir, "entry:").unwrap();
        writeln!(self.ir, "  %act = call double @hill_activation(double %activator, double 1.0, double %ka, double %na)").unwrap();
        writeln!(self.ir, "  %rep = call double @hill_repression(double %repressor, double 1.0, double %kr, double %nr)").unwrap();
        writeln!(self.ir, "  %combined = fmul double %act, %rep").unwrap();
        writeln!(self.ir, "  %result = fmul double %vmax, %combined").unwrap();
        writeln!(self.ir, "  ret double %result").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();

        // Declare LLVM intrinsic
        writeln!(self.ir, "declare double @llvm.pow.f64(double, double) #1").unwrap();
        writeln!(self.ir, "declare double @llvm.fabs.f64(double) #1").unwrap();
        writeln!(self.ir, "declare double @llvm.exp.f64(double) #1").unwrap();
        writeln!(self.ir, "declare double @llvm.log.f64(double) #1").unwrap();
        writeln!(self.ir).unwrap();
    }

    // ─── Circuit Code Generation ──────────────────────────────────────

    fn emit_circuit(&mut self, circuit: &GeneticCircuit) {
        writeln!(self.ir, "; ---- Circuit: {} ----", circuit.name).unwrap();
        writeln!(self.ir, "; TUs: {}, Regulatory links: {}, ATP cost: {:.1}",
            circuit.transcription_units.len(),
            circuit.regulatory_links.len(),
            circuit.estimated_atp_cost
        ).unwrap();
        writeln!(self.ir).unwrap();

        // Generate a function for each transcription unit
        for (i, tu) in circuit.transcription_units.iter().enumerate() {
            self.emit_tu_function(&circuit.name, i, tu, &circuit.regulatory_links);
        }

        // Generate the ODE derivative function for the entire circuit
        self.emit_circuit_derivative(&circuit);

        // Kill switch check
        if circuit.kill_switch.is_some() {
            self.emit_kill_switch(&circuit.name, circuit.kill_switch.as_ref().unwrap());
        }
    }

    fn emit_tu_function(&mut self, circuit_name: &str, tu_index: usize,
                         tu: &TranscriptionUnit, regulations: &[RegulatoryLink]) {
        let fn_name = format!("@{}_tu{}_activity", circuit_name, tu_index);

        writeln!(self.ir, "; Transcription Unit: {} ({})",
            tu.name, tu.promoter.name).unwrap();
        writeln!(self.ir, "; Promoter: {} (strength={:.2}, ΔG={:.1} kcal/mol)",
            tu.promoter.name, tu.promoter.strength, tu.promoter.delta_g).unwrap();
        writeln!(self.ir, "; RBS: {} (rate={:.2})", tu.rbs.name, tu.rbs.translation_rate).unwrap();
        writeln!(self.ir, "; CDS: {} ({} bp, {} aa)",
            tu.cds.name, tu.cds.dna_sequence.len(), tu.cds.amino_sequence.len()).unwrap();

        // Function takes concentrations of all regulators as parameters
        let regulators: Vec<&RegulatoryLink> = regulations.iter()
            .filter(|r| tu.promoter.regulated_by.contains(&r.from) || r.to == tu.name)
            .collect();

        if regulators.is_empty() {
            // Constitutive promoter — just returns basal activity
            writeln!(self.ir, "define double {}(double %time) #0 {{", fn_name).unwrap();
            writeln!(self.ir, "entry:").unwrap();
            writeln!(self.ir, "  ret double {:.6}", tu.promoter.strength).unwrap();
            writeln!(self.ir, "}}").unwrap();
        } else {
            // Regulated promoter — takes regulator concentrations
            let params: Vec<String> = std::iter::once("double %time".to_string())
                .chain(regulators.iter().enumerate().map(|(j, _)| format!("double %reg{}", j)))
                .collect();

            writeln!(self.ir, "define double {}({}) #0 {{",
                fn_name, params.join(", ")).unwrap();
            writeln!(self.ir, "entry:").unwrap();

            // Start with basal promoter strength
            writeln!(self.ir, "  %basal = fadd double 0.0, {:.6}", tu.promoter.strength).unwrap();

            let mut current_reg = "%basal".to_string();
            for (j, reg) in regulators.iter().enumerate() {
                let hill_fn = match reg.regulation_type {
                    LinkType::Activation => "@hill_activation",
                    LinkType::Repression => "@hill_repression",
                    LinkType::Dual => "@hill_activation", // Simplified
                };

                let result = format!("%reg_effect{}", j);
                writeln!(self.ir, "  {} = call double {}(double %reg{}, double {}, double {:.6}, double {:.6})",
                    result, hill_fn, j, current_reg, reg.k_half, reg.hill_coefficient).unwrap();
                current_reg = result;
            }

            writeln!(self.ir, "  ret double {}", current_reg).unwrap();
            writeln!(self.ir, "}}").unwrap();
        }
        writeln!(self.ir).unwrap();
    }

    fn emit_circuit_derivative(&mut self, circuit: &GeneticCircuit) {
        let n_tus = circuit.transcription_units.len();
        if n_tus == 0 { return; }

        writeln!(self.ir, "; ODE system for circuit: {}", circuit.name).unwrap();
        writeln!(self.ir, "; dy/dt = f(t, y) where y = [mRNA_1, protein_1, mRNA_2, protein_2, ...]").unwrap();

        // Function: takes time + state vector, returns derivative vector
        // State: 2 values per TU (mRNA, protein)
        let state_size = n_tus * 2;
        writeln!(self.ir, "define void @{}_derivative(double %t, [{} x double]* %y, [{} x double]* %dydt) #0 {{",
            circuit.name, state_size, state_size).unwrap();
        writeln!(self.ir, "entry:").unwrap();

        for (i, tu) in circuit.transcription_units.iter().enumerate() {
            let mrna_idx = i * 2;
            let prot_idx = i * 2 + 1;

            // Load current mRNA and protein levels
            writeln!(self.ir, "  ; --- TU{}: {} ---", i, tu.name).unwrap();
            writeln!(self.ir, "  %mrna{}_ptr = getelementptr [{} x double], [{} x double]* %y, i64 0, i64 {}",
                i, state_size, state_size, mrna_idx).unwrap();
            writeln!(self.ir, "  %mrna{} = load double, double* %mrna{}_ptr", i, i).unwrap();
            writeln!(self.ir, "  %prot{}_ptr = getelementptr [{} x double], [{} x double]* %y, i64 0, i64 {}",
                i, state_size, state_size, prot_idx).unwrap();
            writeln!(self.ir, "  %prot{} = load double, double* %prot{}_ptr", i, i).unwrap();

            // Transcription rate: promoter_strength * RNAP_speed / gene_length
            let gene_length = tu.cds.dna_sequence.len().max(1) as f64;
            let transcription_rate = tu.promoter.strength * 50.0 / gene_length;

            // mRNA derivative: synthesis - degradation
            // d[mRNA]/dt = k_transcription * promoter_activity - δ_mRNA * [mRNA]
            writeln!(self.ir, "  %txn_rate{} = fmul double {:.8}, 1.0  ; k_transcription = {:.6}",
                i, transcription_rate, transcription_rate).unwrap();
            writeln!(self.ir, "  %mrna_deg{} = fmul double 0.0023, %mrna{}  ; mRNA degradation", i, i).unwrap();
            writeln!(self.ir, "  %d_mrna{} = fsub double %txn_rate{}, %mrna_deg{}", i, i, i).unwrap();

            // Protein derivative: translation - degradation
            // d[Protein]/dt = k_translation * [mRNA] - δ_protein * [Protein]
            let translation_rate = tu.rbs.translation_rate * 15.0; // RBS rate * ribosome speed
            writeln!(self.ir, "  %tln_rate{} = fmul double {:.8}, %mrna{}  ; k_translation * [mRNA]",
                i, translation_rate, i).unwrap();
            writeln!(self.ir, "  %prot_deg{} = fmul double 0.00019, %prot{}  ; protein degradation", i, i).unwrap();
            writeln!(self.ir, "  %d_prot{} = fsub double %tln_rate{}, %prot_deg{}", i, i, i).unwrap();

            // Store derivatives
            writeln!(self.ir, "  %d_mrna{}_ptr = getelementptr [{} x double], [{} x double]* %dydt, i64 0, i64 {}",
                i, state_size, state_size, mrna_idx).unwrap();
            writeln!(self.ir, "  store double %d_mrna{}, double* %d_mrna{}_ptr", i, i).unwrap();
            writeln!(self.ir, "  %d_prot{}_ptr = getelementptr [{} x double], [{} x double]* %dydt, i64 0, i64 {}",
                i, state_size, state_size, prot_idx).unwrap();
            writeln!(self.ir, "  store double %d_prot{}, double* %d_prot{}_ptr", i, i).unwrap();

            writeln!(self.ir).unwrap();
        }

        writeln!(self.ir, "  ret void").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();
    }

    fn emit_kill_switch(&mut self, circuit_name: &str, ks: &KillSwitchIR) {
        writeln!(self.ir, "; Kill Switch for circuit: {}", circuit_name).unwrap();
        writeln!(self.ir, "; Mechanism: {:?}, Delay: {} hours", ks.mechanism, ks.delay_hours).unwrap();

        writeln!(self.ir, "define i1 @{}_kill_switch_active(double %trigger_concentration, double %time) #0 {{",
            circuit_name).unwrap();
        writeln!(self.ir, "entry:").unwrap();

        match &ks.trigger {
            KillTrigger::AbsenceOf(_) => {
                // Kill when trigger concentration drops below threshold
                writeln!(self.ir, "  %below_threshold = fcmp olt double %trigger_concentration, 0.01").unwrap();
                writeln!(self.ir, "  %past_delay = fcmp ogt double %time, {:.2}", ks.delay_hours * 3600.0).unwrap();
                writeln!(self.ir, "  %active = and i1 %below_threshold, %past_delay").unwrap();
            }
            KillTrigger::PresenceOf(_) => {
                writeln!(self.ir, "  %above_threshold = fcmp ogt double %trigger_concentration, 0.1").unwrap();
                writeln!(self.ir, "  %past_delay = fcmp ogt double %time, {:.2}", ks.delay_hours * 3600.0).unwrap();
                writeln!(self.ir, "  %active = and i1 %above_threshold, %past_delay").unwrap();
            }
            KillTrigger::TemperatureAbove(t) => {
                writeln!(self.ir, "  %above_temp = fcmp ogt double %trigger_concentration, {:.1}", t).unwrap();
                writeln!(self.ir, "  %active = and i1 %above_temp, i1 true").unwrap();
            }
            KillTrigger::TemperatureBelow(t) => {
                writeln!(self.ir, "  %below_temp = fcmp olt double %trigger_concentration, {:.1}", t).unwrap();
                writeln!(self.ir, "  %active = and i1 %below_temp, i1 true").unwrap();
            }
            KillTrigger::TimeAfterActivation(t) => {
                writeln!(self.ir, "  %past_time = fcmp ogt double %time, {:.1}", t * 3600.0).unwrap();
                writeln!(self.ir, "  %active = and i1 %past_time, i1 true").unwrap();
            }
        }

        writeln!(self.ir, "  ret i1 %active").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();
    }

    // ─── Simulation Harness ───────────────────────────────────────────

    fn emit_simulation_harness(&mut self, program: &BioIRProgram) {
        writeln!(self.ir, "; ---- Simulation Harness (Euler method ODE solver) ----").unwrap();
        writeln!(self.ir).unwrap();

        for circuit in &program.circuits {
            let n_tus = circuit.transcription_units.len();
            if n_tus == 0 { continue; }
            let state_size = n_tus * 2;

            // Euler integration step
            writeln!(self.ir, "; Euler step for circuit: {}", circuit.name).unwrap();
            writeln!(self.ir, "define void @{}_euler_step(double %t, double %dt, [{} x double]* %state) #0 {{",
                circuit.name, state_size).unwrap();
            writeln!(self.ir, "entry:").unwrap();

            // Allocate derivative vector
            writeln!(self.ir, "  %dydt = alloca [{} x double]", state_size).unwrap();

            // Compute derivatives
            writeln!(self.ir, "  call void @{}_derivative(double %t, [{} x double]* %state, [{} x double]* %dydt)",
                circuit.name, state_size, state_size).unwrap();

            // Update state: y[i] += dt * dydt[i]
            for i in 0..state_size {
                writeln!(self.ir, "  %dy{}_ptr = getelementptr [{} x double], [{} x double]* %dydt, i64 0, i64 {}",
                    i, state_size, state_size, i).unwrap();
                writeln!(self.ir, "  %dy{} = load double, double* %dy{}_ptr", i, i).unwrap();
                writeln!(self.ir, "  %delta{} = fmul double %dt, %dy{}", i, i).unwrap();
                writeln!(self.ir, "  %y{}_ptr = getelementptr [{} x double], [{} x double]* %state, i64 0, i64 {}",
                    i, state_size, state_size, i).unwrap();
                writeln!(self.ir, "  %y{} = load double, double* %y{}_ptr", i, i).unwrap();
                writeln!(self.ir, "  %y{}_new = fadd double %y{}, %delta{}", i, i, i).unwrap();
                // Clamp to non-negative (biological concentrations can't be negative)
                writeln!(self.ir, "  %y{}_clamped = call double @llvm.fabs.f64(double %y{}_new)", i, i).unwrap();
                writeln!(self.ir, "  store double %y{}_clamped, double* %y{}_ptr", i, i).unwrap();
            }

            writeln!(self.ir, "  ret void").unwrap();
            writeln!(self.ir, "}}").unwrap();
            writeln!(self.ir).unwrap();

            // Full simulation function
            writeln!(self.ir, "; Simulate circuit {} for given duration", circuit.name).unwrap();
            writeln!(self.ir, "define %SimResult @{}_simulate(double %duration, double %dt) #0 {{",
                circuit.name).unwrap();
            writeln!(self.ir, "entry:").unwrap();

            // Initialize state to zeros
            writeln!(self.ir, "  %state = alloca [{} x double]", state_size).unwrap();
            for i in 0..state_size {
                writeln!(self.ir, "  %init{}_ptr = getelementptr [{} x double], [{} x double]* %state, i64 0, i64 {}",
                    i, state_size, state_size, i).unwrap();
                writeln!(self.ir, "  store double 0.0, double* %init{}_ptr", i).unwrap();
            }

            // Time loop
            writeln!(self.ir, "  br label %loop").unwrap();
            writeln!(self.ir).unwrap();
            writeln!(self.ir, "loop:").unwrap();
            writeln!(self.ir, "  %t = phi double [ 0.0, %entry ], [ %t_next, %loop_body ]").unwrap();
            writeln!(self.ir, "  %steps = phi i32 [ 0, %entry ], [ %steps_next, %loop_body ]").unwrap();
            writeln!(self.ir, "  %done = fcmp oge double %t, %duration").unwrap();
            writeln!(self.ir, "  br i1 %done, label %exit, label %loop_body").unwrap();
            writeln!(self.ir).unwrap();
            writeln!(self.ir, "loop_body:").unwrap();
            writeln!(self.ir, "  call void @{}_euler_step(double %t, double %dt, [{} x double]* %state)",
                circuit.name, state_size).unwrap();
            writeln!(self.ir, "  %t_next = fadd double %t, %dt").unwrap();
            writeln!(self.ir, "  %steps_next = add i32 %steps, 1").unwrap();
            writeln!(self.ir, "  br label %loop").unwrap();
            writeln!(self.ir).unwrap();
            writeln!(self.ir, "exit:").unwrap();

            // Read final protein levels
            if n_tus > 0 {
                writeln!(self.ir, "  %final_prot_ptr = getelementptr [{} x double], [{} x double]* %state, i64 0, i64 1",
                    state_size, state_size).unwrap();
                writeln!(self.ir, "  %final_prot = load double, double* %final_prot_ptr").unwrap();
            } else {
                writeln!(self.ir, "  %final_prot = fadd double 0.0, 0.0").unwrap();
            }

            writeln!(self.ir, "  %result_0 = insertvalue %SimResult undef, double %t, 0").unwrap();
            writeln!(self.ir, "  %result_1 = insertvalue %SimResult %result_0, double %final_prot, 1").unwrap();
            writeln!(self.ir, "  %result_2 = insertvalue %SimResult %result_1, i32 %steps, 2").unwrap();
            writeln!(self.ir, "  ret %SimResult %result_2").unwrap();
            writeln!(self.ir, "}}").unwrap();
            writeln!(self.ir).unwrap();
        }
    }

    // ─── Main Entry Point ─────────────────────────────────────────────

    fn emit_main(&mut self, program: &BioIRProgram) {
        // Declare printf for output
        writeln!(self.ir, "declare i32 @printf(i8*, ...) #2").unwrap();
        writeln!(self.ir).unwrap();

        // Format strings
        writeln!(self.ir, "@.str_header = private constant [50 x i8] c\"SynBio-LLVM Simulation: %s\\0A======================\\0A\\00\"").unwrap();
        writeln!(self.ir, "@.str_result = private constant [60 x i8] c\"  Time: %.2f s | Protein: %.2f copies | Steps: %d\\0A\\00\"").unwrap();
        writeln!(self.ir, "@.str_name = private constant [{} x i8] c\"{}\\00\"",
            program.name.len() + 1, program.name).unwrap();
        writeln!(self.ir).unwrap();

        // Main function
        writeln!(self.ir, "define i32 @main() #0 {{").unwrap();
        writeln!(self.ir, "entry:").unwrap();

        // Print header
        writeln!(self.ir, "  %header = getelementptr [50 x i8], [50 x i8]* @.str_header, i64 0, i64 0").unwrap();
        writeln!(self.ir, "  %name = getelementptr [{} x i8], [{} x i8]* @.str_name, i64 0, i64 0",
            program.name.len() + 1, program.name.len() + 1).unwrap();
        writeln!(self.ir, "  call i32 (i8*, ...) @printf(i8* %header, i8* %name)").unwrap();

        // Run simulation for each circuit
        for circuit in &program.circuits {
            if circuit.transcription_units.is_empty() { continue; }

            writeln!(self.ir).unwrap();
            writeln!(self.ir, "  ; Simulate circuit: {}", circuit.name).unwrap();
            writeln!(self.ir, "  %sim_{} = call %SimResult @{}_simulate(double 3600.0, double 1.0)",
                circuit.name, circuit.name).unwrap();
            writeln!(self.ir, "  %time_{} = extractvalue %SimResult %sim_{}, 0",
                circuit.name, circuit.name).unwrap();
            writeln!(self.ir, "  %prot_{} = extractvalue %SimResult %sim_{}, 1",
                circuit.name, circuit.name).unwrap();
            writeln!(self.ir, "  %steps_{} = extractvalue %SimResult %sim_{}, 2",
                circuit.name, circuit.name).unwrap();

            writeln!(self.ir, "  %fmt = getelementptr [60 x i8], [60 x i8]* @.str_result, i64 0, i64 0").unwrap();
            writeln!(self.ir, "  call i32 (i8*, ...) @printf(i8* %fmt, double %time_{}, double %prot_{}, i32 %steps_{})",
                circuit.name, circuit.name, circuit.name).unwrap();
        }

        writeln!(self.ir, "  ret i32 0").unwrap();
        writeln!(self.ir, "}}").unwrap();
        writeln!(self.ir).unwrap();
    }

    // ─── Metadata ─────────────────────────────────────────────────────

    fn emit_metadata(&mut self, program: &BioIRProgram) {
        writeln!(self.ir, "; ---- Module Metadata ----").unwrap();
        writeln!(self.ir, "attributes #0 = {{ nounwind }}").unwrap();
        writeln!(self.ir, "attributes #1 = {{ nounwind readnone }}").unwrap();
        writeln!(self.ir, "attributes #2 = {{ nounwind }}").unwrap();
        writeln!(self.ir).unwrap();

        writeln!(self.ir, "!llvm.module.flags = !{{!0, !1}}").unwrap();
        writeln!(self.ir, "!llvm.ident = !{{!2}}").unwrap();
        writeln!(self.ir).unwrap();
        writeln!(self.ir, "!0 = !{{i32 1, !\"wchar_size\", i32 4}}").unwrap();
        writeln!(self.ir, "!1 = !{{i32 7, !\"PIC Level\", i32 2}}").unwrap();
        writeln!(self.ir, "!2 = !{{!\"SynBio-LLVM Compiler v0.9.0\"}}").unwrap();
        writeln!(self.ir).unwrap();

        // Custom biological metadata
        writeln!(self.ir, "; ---- Biological Metadata ----").unwrap();
        if let Some(ref host) = program.host {
            writeln!(self.ir, "; Host: {} (doubling time: {:.0} min)", host.name, host.doubling_time_minutes).unwrap();
        }
        for circuit in &program.circuits {
            writeln!(self.ir, "; Circuit '{}': {} TUs, ATP cost: {:.1}, toxicity: {:.2}",
                circuit.name,
                circuit.transcription_units.len(),
                circuit.estimated_atp_cost,
                circuit.toxicity_score
            ).unwrap();
            if circuit.is_contained {
                writeln!(self.ir, ";   Containment: YES (kill switch present)").unwrap();
            }
        }
    }
}

