    /**
     * Export SBOL locally
     */
    async exportAsSBOL(): Promise<void> {
        const editor = vscode.window.activeTextEditor;
        if (!editor) {
            vscode.window.showWarningMessage('Abre un archivo .bio para exportar');
            return;
        }

        const code = editor.document.getText();
        const parts = parseBioScriptForExport(code);

        if (parts.length === 0) {
            vscode.window.showWarningMessage('No se pudieron extraer partes del BioScript');
            return;
        }

        const name = parts[0]?.displayId || 'circuit';
        const sbol = generateSBOL3(parts, name, 'https://synbio-llvm.dev/designs');

        const uri = await vscode.window.showSaveDialog({
            defaultUri: vscode.Uri.file(`${name}.sbol.xml`),
            filters: {
                'SBOL 3.0 XML': ['xml', 'sbol'],
                'All Files': ['*'],
            },
        });

        if (uri) {
            await vscode.workspace.fs.writeFile(uri, Buffer.from(sbol, 'utf-8'));
            vscode.window.showInformationMessage(`✅ SBOL 3.0 exportado: ${uri.fsPath} (${parts.length} parts)`);
        }
    }

    /**
     * Save SBOL locally (used by publish flow)
     */
    private async saveSBOLLocally(parts: SBOLPart[], collectionName: string): Promise<void> {
        const sbol = generateSBOL3(parts, collectionName, 'https://synbio-llvm.dev/designs');

        const uri = await vscode.window.showSaveDialog({
            defaultUri: vscode.Uri.file(`${collectionName}.sbol.xml`),
            filters: { 'SBOL 3.0': ['xml', 'sbol'] },
        });

        if (uri) {
            await vscode.workspace.fs.writeFile(uri, Buffer.from(sbol, 'utf-8'));
            vscode.window.showInformationMessage(`✅ SBOL guardado: ${uri.fsPath}`);
        }
    }

    /**
     * Search SynBioHub for existing parts
     */
    async searchRegistry(): Promise<void> {
        const term = await vscode.window.showInputBox({
            title: '🔍 Buscar en SynBioHub',
            prompt: 'Término de búsqueda',
            placeHolder: 'Ej: toggle switch, GFP reporter, kill switch',
        });

        if (!term) { return; }

        await vscode.window.withProgress({
            location: vscode.ProgressLocation.Notification,
            title: '🔍 Buscando en SynBioHub...',
            cancellable: true,
        }, async () => {
            try {
                const url = `https://synbiohub.org/search/${encodeURIComponent(term)}&offset=0&limit=20`;
                const response = await fetch(url, {
                    headers: { 'Accept': 'application/json' },
                });

                if (!response.ok) {
                    throw new Error(`Search failed: ${response.status}`);
                }

                const results = await response.json() as any[];

                if (!results || results.length === 0) {
                    vscode.window.showInformationMessage(`No se encontraron resultados para "${term}"`);
                    return;
                }

                const items = results.slice(0, 20).map((r: any) => ({
                    label: `$(file-code) ${r.displayId || r.name || 'Unknown'}`,
                    description: r.version || '',
                    detail: r.description || r.name || 'Sin descripción',
                    url: r.uri || '',
                }));

                const selected = await vscode.window.showQuickPick(items, {
                    title: `🔍 SynBioHub: ${results.length} resultados para "${term}"`,
                    placeHolder: 'Selecciona para ver detalles',
                    matchOnDetail: true,
                });

                if (selected && selected.url) {
                    const action = await vscode.window.showInformationMessage(
                        `${selected.label}: ${selected.detail}`,
                        'Abrir en Navegador',
                        'Descargar SBOL'
                    );

                    if (action === 'Abrir en Navegador') {
                        vscode.env.openExternal(vscode.Uri.parse(selected.url));
                    } else if (action === 'Descargar SBOL') {
                        const sbolUrl = `${selected.url}/sbol`;
                        const sbolResp = await fetch(sbolUrl);
                        if (sbolResp.ok) {
                            const sbolContent = await sbolResp.text();
                            const doc = await vscode.workspace.openTextDocument({
                                content: sbolContent,
                                language: 'xml',
                            });
                            await vscode.window.showTextDocument(doc);
                        }
                    }
                }

            } catch (err) {
                vscode.window.showErrorMessage(`Error buscando: ${err instanceof Error ? err.message : String(err)}`);
            }
        });
    }

    /**
     * Import a design from SynBioHub
     */
    async importFromRegistry(): Promise<void> {
        const url = await vscode.window.showInputBox({
            title: '📥 Importar desde SynBioHub',
            prompt: 'URL del diseño en SynBioHub',
            placeHolder: 'https://synbiohub.org/public/igem/BBa_K314103/1',
        });

        if (!url) { return; }

        await vscode.window.withProgress({
            location: vscode.ProgressLocation.Notification,
            title: '📥 Importando desde SynBioHub...',
            cancellable: true,
        }, async () => {
            try {
                const sbolUrl = url.endsWith('/sbol') ? url : `${url}/sbol`;
                const response = await fetch(sbolUrl);

                if (!response.ok) {
                    throw new Error(`Import failed: ${response.status}`);
                }

                const sbol = await response.text();

                const doc = await vscode.workspace.openTextDocument({
                    content: sbol,
                    language: 'xml',
                });
                await vscode.window.showTextDocument(doc);

                vscode.window.showInformationMessage(`✅ SBOL importado (${sbol.length} bytes)`);

            } catch (err) {
                vscode.window.showErrorMessage(`Error: ${err instanceof Error ? err.message : String(err)}`);
            }
        });
    }

    dispose(): void {
        this.outputChannel.dispose();
        this.disposables.forEach(d => d.dispose());
    }
