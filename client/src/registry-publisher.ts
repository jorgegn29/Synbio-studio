/**
 * ══════════════════════════════════════════════════════════════════════════════
 * Registry Publisher — Export Circuits to SynBioHub, iGEM & Addgene
 * ══════════════════════════════════════════════════════════════════════════════
 *
 * Enables direct publication of BioScript designs to standard biological
 * parts registries:
 *
 *   1. SynBioHub — SBOL 3.0 design repository (primary target)
 *   2. iGEM Registry — International Genetically Engineered Machine parts
 *   3. Addgene — Plasmid repository (generates submission form)
 *
 * SynBioHub REST API:
 *   - POST /login          → authenticate
 *   - POST /submit         → upload SBOL design
 *   - GET  /search         → search existing parts
 *   - GET  /<uri>/sbol     → download SBOL
 *
 * References:
 *   - SynBioHub API: https://wiki.synbiohub.org/api-docs
 *   - SBOL 3.0: https://sbolstandard.org/
 *   - iGEM Registry: http://parts.igem.org/
 * ══════════════════════════════════════════════════════════════════════════════
 */

