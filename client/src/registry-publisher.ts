interface SBOLPart {
    displayId: string;
    name: string;
    description: string;
    type: 'promoter' | 'rbs' | 'cds' | 'terminator' | 'gene' | 'circuit' | 'plasmid';
    sequence?: string;
    role: string; // SO URI
}

const SO_ROLES: Record<string, string> = {
    promoter: 'http://identifiers.org/SO:0000167',
    rbs: 'http://identifiers.org/SO:0000139',
    cds: 'http://identifiers.org/SO:0000316',
    terminator: 'http://identifiers.org/SO:0000141',
    gene: 'http://identifiers.org/SO:0000704',
    circuit: 'http://identifiers.org/SO:0000804',
    plasmid: 'http://identifiers.org/SO:0000155',
    operator: 'http://identifiers.org/SO:0000057',
    origin: 'http://identifiers.org/SO:0000296',
};

function generateSBOL3(parts: SBOLPart[], collectionName: string, namespace: string): string {
    const timestamp = new Date().toISOString();

    let sbol = `<?xml version="1.0" encoding="UTF-8"?>
<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"
         xmlns:sbol="http://sbols.org/v3#"
         xmlns:dcterms="http://purl.org/dc/terms/"
         xmlns:prov="http://www.w3.org/ns/prov#"
         xmlns:om="http://www.ontology-of-units-of-measure.org/resource/om-2/"
         xmlns:synbio="https://synbio-llvm.dev/ns#">

  <!-- ═══════════════════════════════════════════════════ -->
  <!-- Collection: ${collectionName} -->
  <!-- Generated by SynBio-LLVM v0.6.0 -->
  <!-- ${timestamp} -->
  <!-- ═══════════════════════════════════════════════════ -->

  <sbol:Collection rdf:about="${namespace}/${collectionName}">
    <sbol:displayId>${collectionName}</sbol:displayId>
    <dcterms:title>${collectionName}</dcterms:title>
    <dcterms:description>Genetic circuit designed with SynBio-LLVM IDE</dcterms:description>
    <dcterms:created>${timestamp}</dcterms:created>
    <prov:wasGeneratedBy>
      <prov:Activity>
        <dcterms:title>SynBio-LLVM Circuit Design</dcterms:title>
        <prov:qualifiedAssociation>
          <prov:Association>
            <prov:agent>
              <prov:Agent rdf:about="https://synbio-llvm.dev">
                <dcterms:title>SynBio-LLVM v0.6.0</dcterms:title>
              </prov:Agent>
            </prov:agent>
          </prov:Association>
        </prov:qualifiedAssociation>
      </prov:Activity>
    </prov:wasGeneratedBy>
`;

    // Add member references
    for (const part of parts) {
        sbol += `    <sbol:member rdf:resource="${namespace}/${collectionName}/${part.displayId}"/>\n`;
    }
    sbol += `  </sbol:Collection>\n\n`;

    // Add each component
    for (const part of parts) {
        sbol += `  <sbol:Component rdf:about="${namespace}/${collectionName}/${part.displayId}">
    <sbol:displayId>${part.displayId}</sbol:displayId>
    <dcterms:title>${part.name}</dcterms:title>
    <dcterms:description>${part.description}</dcterms:description>
    <sbol:type rdf:resource="http://identifiers.org/SBO:0000251"/>
    <sbol:role rdf:resource="${part.role}"/>
`;
        if (part.sequence) {
            sbol += `    <sbol:hasSequence rdf:resource="${namespace}/${collectionName}/${part.displayId}_seq"/>\n`;
        }
        sbol += `  </sbol:Component>\n\n`;

        // Add sequence if available
        if (part.sequence) {
            sbol += `  <sbol:Sequence rdf:about="${namespace}/${collectionName}/${part.displayId}_seq">
    <sbol:displayId>${part.displayId}_seq</sbol:displayId>
    <sbol:elements>${part.sequence}</sbol:elements>
    <sbol:encoding rdf:resource="http://identifiers.org/edam:format_1207"/>
  </sbol:Sequence>\n\n`;
        }
    }

    sbol += `</rdf:RDF>`;
    return sbol;
}

// ════════════════════════════════════════════════════════════════════════════
// BIOSCRIPT PARSER (extract parts for SBOL export)
// ════════════════════════════════════════════════════════════════════════════

function parseBioScriptForExport(code: string): SBOLPart[] {
    const parts: SBOLPart[] = [];

    // Extract circuit name
    const circuitMatch = code.match(/circuit\s+(\w+)/);
    if (circuitMatch) {
        parts.push({
            displayId: circuitMatch[1],
            name: circuitMatch[1],
            description: 'Genetic circuit designed in BioScript',
            type: 'circuit',
            role: SO_ROLES.circuit,
        });
    }

    // Extract promoters
    const promoterRegex = /promoter\s+(\w+)\s*\{([^}]*)\}/g;
    let match;
    while ((match = promoterRegex.exec(code)) !== null) {
        const body = match[2];
        const typeMatch = body.match(/type:\s*"?(\w+)"?/);
        parts.push({
            displayId: match[1],
            name: match[1],
            description: `${typeMatch?.[1] || 'unknown'} promoter`,
            type: 'promoter',
            role: SO_ROLES.promoter,
        });
    }

    // Extract genes
    const geneRegex = /gene\s+(\w+)\s*\{([^}]*)\}/g;
    while ((match = geneRegex.exec(code)) !== null) {
        const body = match[2];
        const productMatch = body.match(/product:\s*"?(\w+)"?/);
        const seqMatch = body.match(/sequence:\s*"([ATCG]+)"/i);
        parts.push({
            displayId: match[1],
            name: match[1],
            description: `Gene encoding ${productMatch?.[1] || 'unknown protein'}`,
            type: 'gene',
            role: SO_ROLES.cds,
            sequence: seqMatch?.[1],
        });
    }

    // Extract kill switches
    const killRegex = /kill_switch\s*\{([^}]*)\}/g;
    while ((match = killRegex.exec(code)) !== null) {
        const body = match[1];
        const toxinMatch = body.match(/toxin:\s*(\w+)/);
        parts.push({
            displayId: 'kill_switch',
            name: `Kill Switch (${toxinMatch?.[1] || 'unknown'})`,
            description: 'Biocontainment kill switch module',
            type: 'gene',
            role: SO_ROLES.cds,
        });
    }

    return parts;
}

